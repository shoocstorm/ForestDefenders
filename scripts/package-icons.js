import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const ICONS = join(ROOT, 'assets/icon');

if (!process.argv[2]) {
  console.error('Usage: bun scripts/package-icons.js <outdir>');
  console.error('  <outdir> is relative to project root (e.g. . for root, dist for build)');
  process.exit(1);
}
const OUT_DIR = join(ROOT, process.argv[2]);
const IS_DEV = OUT_DIR === ROOT; // Root dir = dev mode

