mkdirSync(OUT_DIR, { recursive: true });

const magic = Buffer.from('FDIC', 'ascii');
const countBuf = Buffer.alloc(4);

const entries = ICON_DEFS.map(({ key, path }) => {
  const data = readFileSync(join(ICONS, path), 'utf-8');
  const keyBuf = Buffer.from(key, 'utf-8');
  const header = Buffer.alloc(2 + keyBuf.length + 4);
  let off = 0;
  header.writeUInt16LE(keyBuf.length, off); off += 2;
  header.set(keyBuf, off); off += keyBuf.length;
  header.writeUInt32LE(Buffer.byteLength(data, 'utf8'), off);
  return { header, data, name: key };
});

countBuf.writeUInt32LE(entries.length, 0);

const bundle = Buffer.concat([
  magic,
  countBuf,
  ...entries.flatMap(e => [e.header, Buffer.from(e.data, 'utf8')])
]);

writeFileSync(join(OUT_DIR, 'icons.bundle'), bundle);
const rel = join(OUT_DIR.replace(ROOT + '/', ''), 'icons.bundle');
console.log(`Wrote ${entries.length} icons (${(bundle.length / 1024).toFixed(1)} KB) → ${rel}`);

// For dev mode, also write an inline Icon.js that bundles the icons directly
if (IS_DEV) {
  const iconSrcPath = join(ROOT, 'src/ui/Icon.js');
  const inlineIconPath = join(ROOT, 'src/ui/Icon.bundle.js');

  // Read the original Icon.js
  let iconJs = readFileSync(iconSrcPath, 'utf-8');

  // Check if there's already a bundle version
  if (existsSync(inlineIconPath)) {
    // Restore the original if it exists (was swapped)
    const original = readFileSync(inlineIconPath, 'utf-8');
    // Only restore if it looks like the original (has loadBundle function)
    if (original.includes('async function loadBundle()')) {
      writeFileSync(iconSrcPath, original);
    }
  }

  // Backup the original
  writeFileSync(inlineIconPath, iconJs);

  // Generate inline version with bundle data
  const bundleBase64 = bundle.toString('base64');
  const inlineIconJs = `// Auto-generated by scripts/package-icons.js (dev mode with inline bundle)
// To restore: mv src/ui/Icon.bundle.js src/ui/Icon.js

let ICONS = {};
let bundleLoaded = false;

function parseBundle(base64) {
  const binaryString = atob(base64);
  const buffer = new Uint8Array(binaryString.length);
  for (let i = 0; i < binaryString.length; i++) {
    buffer[i] = binaryString.charCodeAt(i);
  }

  const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
  let offset = 0;

  // Verify magic
  const magicBytes = buffer.subarray(offset, offset + 4);
  const magic = new TextDecoder().decode(magicBytes);
  if (magic !== 'FDIC') throw new Error('Invalid icons bundle format');
  offset += 4;

  // Read count
  const count = view.getUint32(offset, true);
  offset += 4;

  const result = {};
  for (let i = 0; i < count; i++) {
    // Read key length and key
    const keyLen = view.getUint16(offset, true);
    offset += 2;
    const keyBytes = buffer.subarray(offset, offset + keyLen);
    const key = new TextDecoder().decode(keyBytes);
    offset += keyLen;

    // Read data length and data
    const dataLen = view.getUint32(offset, true);
    offset += 4;
    const dataBytes = buffer.subarray(offset, offset + dataLen);
    const data = new TextDecoder().decode(dataBytes);
    offset += dataLen;

    // Convert to data URL for use with mask-image
    const base64Data = btoa(data);
    result[key] = 'data:image/svg+xml;base64,' + base64Data;
  }

  return result;
}

// Load bundle immediately from inline data
try {
  ICONS = parseBundle('${bundleBase64}');
  bundleLoaded = true;
} catch (e) {
  console.error('Failed to parse inline icon bundle:', e);
}

// Returns markup for a tinted icon span. 'name' must be a key in ICONS.
export function icon(name, { className = '', style = '' } = {}) {
  const url = ICONS[name];
  if (!url) throw new Error('icon(): unknown icon "' + name + '"');
  const cls = className ? 'fd-icon ' + className : 'fd-icon';
  return '<span class="' + cls + '" style="-webkit-mask-image:url(\\'' + url + '\\');mask-image:url(\\'' + url + '\\');' + style + '"></span>';
}
`;

  writeFileSync(iconSrcPath, inlineIconJs);
  console.log('Generated inline Icon.js for dev mode');
} else {
  // Production mode: restore original Icon.js (fetch-based)
  const iconSrcPath = join(ROOT, 'src/ui/Icon.js');
  const inlineIconPath = join(ROOT, 'src/ui/Icon.bundle.js');

  if (existsSync(inlineIconPath)) {
    const original = readFileSync(inlineIconPath, 'utf-8');
    if (original.includes('async function loadBundle()')) {
      writeFileSync(iconSrcPath, original);
      console.log('Restored fetch-based Icon.js for production build');
    }
  }
}
